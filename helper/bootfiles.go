package main

import (
	"bytes"
	"embed"
	"fmt"
	"io"
	"io/fs"
	"net/http"
	"path"
	"strings"
	"sync"
	"time"
)

// The build copies lpxelinux.0, ldlinux.c32, the c32 modules, vmlinuz and
// retro.gz into helper/bootfiles/ before go build (CONTRACTS.md section 5).
// The placeholder README.md keeps the pattern valid when nothing was copied.
//
//go:embed bootfiles/*
var embeddedBoot embed.FS

const pxeConfigPath = "pxelinux.cfg/default"

// pxeConfigTemplate: %[1]s is the helper base URL http://IP:PORT. The
// "retro" APPEND line is the exact one of CONTRACTS.md section 5; "safe"
// adds the same switches as the USB menu's safe entry.
const pxeConfigTemplate = `# generated by retro-helper %[2]s at start-up; not stored on disk
DEFAULT retro
PROMPT 1
TIMEOUT 50
SAY retro-backup: booting in 5 s. Type "safe" + Enter for acpi=off noapic nolapic.
LABEL retro
  KERNEL %[1]s/boot/vmlinuz
  APPEND initrd=%[1]s/boot/retro.gz quiet nomodeset vga=788 vt.default_utf8=1 norestore noswap nodhcp base rootfstype=ramfs retro.boot=pxe retro.dest=%[1]s
LABEL safe
  KERNEL %[1]s/boot/vmlinuz
  APPEND initrd=%[1]s/boot/retro.gz quiet nomodeset vga=normal vt.default_utf8=1 norestore noswap nodhcp base rootfstype=ramfs retro.boot=pxe retro.dest=%[1]s acpi=off noapic nolapic
`

// bootFiles serves the TFTP root, which is also HTTP /boot/.
type bootFiles struct {
	fsys     fs.FS
	config   []byte
	started  time.Time
	missing  bool
	warnOnce sync.Once
}

func pxeConfig(baseURL, version string) []byte {
	return []byte(fmt.Sprintf(pxeConfigTemplate, baseURL, version))
}

func newBootFiles(fsys fs.FS, baseURL, version string) *bootFiles {
	b := &bootFiles{fsys: fsys, config: pxeConfig(baseURL, version), started: time.Now()}
	if _, err := fs.Stat(fsys, "lpxelinux.0"); err != nil {
		b.missing = true
	}
	return b
}

func embeddedBootFS() fs.FS {
	sub, err := fs.Sub(embeddedBoot, "bootfiles")
	if err != nil {
		panic(err)
	}
	return sub
}

// warnMissing logs the missing-boot-files hint once per run.
func (b *bootFiles) warnMissing() {
	if b.missing {
		b.warnOnce.Do(func() {
			logf("WARN boot files missing, run make helper (lpxelinux.0 is not embedded; PXE requests get 404)")
		})
	}
}

// cleanName normalises a requested name; ok is false for anything outside
// the root.
func cleanName(name string) (string, bool) {
	name = strings.ReplaceAll(name, "\\", "/")
	name = strings.TrimLeft(name, "/")
	if name == "" {
		return "", false
	}
	for _, p := range strings.Split(name, "/") {
		if p == ".." {
			return "", false
		}
	}
	c := path.Clean(name)
	return c, fs.ValidPath(c) && c != "."
}

// open returns the content of a boot file and its size.
func (b *bootFiles) open(name string) (io.ReadSeeker, int64, func(), error) {
	c, ok := cleanName(name)
	if !ok {
		return nil, 0, nil, fs.ErrNotExist
	}
	if c == pxeConfigPath {
		return bytes.NewReader(b.config), int64(len(b.config)), func() {}, nil
	}
	f, err := b.fsys.Open(c)
	if err != nil {
		return nil, 0, nil, err
	}
	fi, err := f.Stat()
	if err != nil || fi.IsDir() {
		f.Close()
		return nil, 0, nil, fs.ErrNotExist
	}
	rs, ok := f.(io.ReadSeeker)
	if !ok {
		f.Close()
		return nil, 0, nil, fmt.Errorf("%s is not seekable", c)
	}
	return rs, fi.Size(), func() { f.Close() }, nil
}

// ServeHTTP serves /boot/<name> with Range support.
func (b *bootFiles) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	if !allowMethods(w, r, http.MethodGet, http.MethodHead) {
		return
	}
	rs, _, closeFn, err := b.open(r.URL.Path)
	if err != nil {
		http.NotFound(w, r)
		return
	}
	defer closeFn()
	http.ServeContent(w, r, path.Base(r.URL.Path), b.started, rs)
}
